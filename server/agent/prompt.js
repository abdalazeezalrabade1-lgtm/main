export function dynamicSystem({ config, memoryBlock, source }) {
  const nowStr = new Intl.DateTimeFormat("ar-SA-u-ca-gregory-nu-latn", {
    dateStyle: "full", timeStyle: "short", timeZone: config.timezone,
  }).format(new Date());
  const tools = [
    config.webSearchEnabled ? "- البحث عبر الإنترنت: متاح (web_search)." : "- البحث عبر الإنترنت: غير متاح في هذا الإعداد. لا تدّعِ البحث.",
    "- البريد، التقويم الخارجي، المتجر (سلة/Shopify)، واتساب/Slack: غير موصولة.",
  ];
  return [
    `التاريخ والوقت الآن: ${nowStr} (${config.timezone}) — ISO: ${new Date().toISOString()}`,
    source === "schedule"
      ? "هذا تشغيل مجدول تلقائي بلا مستخدم حاضر: لا تطرح أسئلة؛ نفّذ ما يمكن، واكتب ملخصًا واضحًا للنتائج وما تعذّر. لا تنشئ مهام مجدولة جديدة."
      : "هذه محادثة مباشرة مع المستخدم.",
    "الأدوات والتكاملات:",
    ...tools,
    "",
    "الذاكرة الدائمة:",
    memoryBlock,
  ].join("\n");
}
